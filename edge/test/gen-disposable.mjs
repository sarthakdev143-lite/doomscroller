// Regenerates functions/_lib/disposable-domains.js from the vendored blocklist the Python side uses
// (saas/security/data/disposable_domains.txt, CC0, see saas/security/data/SOURCE.txt).
// Run: npm run gen:disposable   (after refreshing that .txt file)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, "../../saas/security/data/disposable_domains.txt");
const out = resolve(here, "../functions/_lib/disposable-domains.js");

const domains = [...new Set(readFileSync(src, "utf8").split(/\r?\n/)
  .map((l) => l.trim().toLowerCase())
  .filter((l) => l && !l.startsWith("#")))];
for (const d of domains) {
  if (!/^[a-z0-9.-]+\.[a-z0-9-]+$/.test(d)) throw new Error(`unexpected entry in blocklist: ${JSON.stringify(d)}`);
}
domains.sort();
const body = `// GENERATED by test/gen-disposable.mjs from saas/security/data/disposable_domains.txt. Do not edit.
// Source: github.com/disposable-email-domains/disposable-email-domains (CC0 1.0 public domain dedication).
// ${domains.length} domains, newline-separated.
export default \`${domains.join("\n")}\`;
`;
writeFileSync(out, body, "utf8");
console.log(`wrote ${domains.length} domains to ${out}`);
